// The board adds Bomb-vs-shatterable pairs the E list did not cover.
const AUTO_BOMB_SHATTER: readonly MaterialName[] = [];

function pairKey(a: MaterialName, b: MaterialName): string {
  return a < b ? `${a}|${b}` : `${b}|${a}`;
}

const SPECIAL = new Map<string, readonly [ReactionSymbol, string]>();
for (const [a, b, s, w] of EXPLICIT) SPECIAL.set(pairKey(a, b), [s, w]);
for (const nm of AUTO_BOMB_SHATTER) {
  const key = pairKey("Bomb", nm);
  if (!SPECIAL.has(key)) SPECIAL.set(key, ["X", "shatters"]);
}

const NO_REACTION = ["." , "no reaction"] as const;

// Fallback engine, same rule order as the board: inert, explosion-when-lit,
// ignition, heat melt, chill freeze, acid, dissolve, absorb, density, conduct.
function fallback(a: MaterialName, b: MaterialName): readonly [ReactionSymbol, string] {
  const A = MATERIALS[a];
  const B = MATERIALS[b];
  if (A.inert || B.inert) return NO_REACTION;
  const both: readonly (readonly [MaterialProps, MaterialProps, MaterialName])[] = [
    [A, B, b], [B, A, a],
  ];
  for (const [X, Y] of both) {
    if (X.explode && Y.ignite > 0) return ["X", "explodes"];
  }
  for (const [X, Y] of both) {
    if (X.ignite > 0 && Y.fuel > 0) return ["B", "ignites"];
  }
  for (const [X, Y] of both) {
    if (X.heat > 0 && Y.melt <= X.heat) return ["M", "melts"];
  }
  for (const [X, Y] of both) {
    if (X.chill > 0 && Y.freezable) return ["F", "freezes"];
  }
  for (const [X, Y] of both) {
    if (X.acidic && Y.acidvuln > 0) return ["D", "corrodes"];
  }
  for (const [X, , yn] of both) {
    if (X.soluble && (yn === "Water" || yn === "Rain" || yn === "Steam")) return ["D", "dissolves"];
  }
  for (const [X, Y] of both) {
    if (X.absorb && Y.state === "liquid" && X !== Y) return ["R", "soaks in"];
  }
  const fluid = (s: MaterialState): boolean => s === "liquid" || s === "gas";
  if (fluid(A.state) && fluid(B.state) && Math.abs(A.dens - B.dens) > 0.3) {
    return ["^", "separates by density"];
  }
  if (A.state === "solid" && B.state === "liquid" && A.dens < B.dens * 0.9) return ["^", "floats"];
  if (B.state === "solid" && A.state === "liquid" && B.dens < A.dens * 0.9) return ["^", "floats"];
  for (const [X, Y] of both) {
    if (X.conduct && Y.state === "energy") return ["R", "conducts"];
  }
  return NO_REACTION;
}

/** Reaction for any unordered pair, including a material meeting itself. */
export function reaction(a: MaterialName, b: MaterialName): readonly [ReactionSymbol, string] {
  return SPECIAL.get(pairKey(a, b)) ?? fallback(a, b);
}

